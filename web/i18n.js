function detectLanguage() {
  try {
    const saved = localStorage.getItem(LANGUAGE_KEY);
    if (LANGUAGES.includes(saved)) return saved;
  } catch { /* Fall back to the browser language. */ }
  return (navigator.languages || [navigator.language]).some((value) => /^ko\b/i.test(value || "")) ? "ko" : "en";
}

export let language = detectLanguage();
document.documentElement.lang = language;

export function t(key, params = {}) {
  const template = messages[language][key] ?? messages.ko[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

export function applyTranslations(root = document) {
  document.documentElement.lang = language;
  root.querySelectorAll("[data-i18n]").forEach((node) => { node.textContent = t(node.dataset.i18n); });
  root.querySelectorAll("[data-i18n-html]").forEach((node) => { node.innerHTML = t(node.dataset.i18nHtml); });
  root.querySelectorAll("[data-i18n-attr]").forEach((node) => {
    for (const pair of node.dataset.i18nAttr.split(";")) {
      const [attribute, key] = pair.split(":");
      if (attribute && key) node.setAttribute(attribute.trim(), t(key.trim()));
    }
  });
}

export function setLanguage(next) {
  if (!LANGUAGES.includes(next)) return false;
  language = next;
  try { localStorage.setItem(LANGUAGE_KEY, next); } catch { /* The choice still applies to this page. */ }
  applyTranslations();
  window.dispatchEvent(new CustomEvent("albumdeck:languagechange", { detail: { language } }));
  return true;
}
